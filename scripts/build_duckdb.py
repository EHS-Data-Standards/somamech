def resolve_kb_dir(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit)
    if DEFAULT_KB_DIR.exists() and any(DEFAULT_KB_DIR.glob("*.yaml")):
        return DEFAULT_KB_DIR
    print(
        f"note: {DEFAULT_KB_DIR.relative_to(ROOT)} is empty, "
        f"building from {FALLBACK_KB_DIR.relative_to(ROOT)} instead",
        file=sys.stderr,
    )
    return FALLBACK_KB_DIR


def default_schema() -> str:
    from importlib.resources import files as pkg_files

    return str(pkg_files("soma") / "schema" / "soma.yaml")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--kb-dir")
    ap.add_argument("--output", default=str(DEFAULT_OUT))
    ap.add_argument("--schema", default=None)
    ap.add_argument("--tsv-dir", help="also dump every table/view as TSV here")
    ap.add_argument("--ddl-only", action="store_true", help="print DDL + views, build nothing")
    args = ap.parse_args(argv)

    schema_path = args.schema or default_schema()
    if args.ddl_only:
        sv = load_schema(schema_path)
        print(emit_ddl(sv))
        print(emit_views(sv))
        return 0

    kb_dir = resolve_kb_dir(args.kb_dir)
    out = Path(args.output)
    result = build(kb_dir, out, schema_path)

    print(f"Built {out} from {result['files']} files in {kb_dir}")
    nonempty = {k: v for k, v in sorted(result["counts"].items()) if v}
    print(f"{len(nonempty)} non-empty tables, {sum(nonempty.values())} rows")
    for k, v in sorted(nonempty.items(), key=lambda kv: -kv[1])[:12]:
        print(f"    {k:34} {v:6}")
    for w in result["warnings"][:10]:
        print(f"  WARNING: {w}", file=sys.stderr)

    if args.tsv_dir:
        written = dump_tsv(out, Path(args.tsv_dir))
        print(f"Wrote {len(written)} TSV files to {args.tsv_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
