def emit_views(sv) -> str:
    """Generate the analysis views.

    These exist so a question like "every ciliary beat frequency measured under
    PM2.5" does not require knowing that assays are split across 11 tables and
    outputs across 11 more.
    """
    assays = _subclasses(sv, "Assay")
    outputs = _subclasses(sv, "AssayOutputMeasurement")
    parts = []

    parts.append(_union_view(sv, "assay", "Assay", assays, "assay_type"))
    parts.append(
        _union_view(
            sv, "assay_output", "AssayOutputMeasurement", outputs, "output_type",
            extra=[("assay_id", '"parent_id"')],
        )
    )

    parts.append("""
-- Every number in the KB with its full experimental context: which paper,
-- which assay, which exposure, which experimental group, which key event.
-- This is the flagship table for analysis and the headline TSV export.
CREATE VIEW measurement_full AS
SELECT
    m.paper_id,
    p.reference_title,
    a.assay_type,
    a.id            AS assay_id,
    a.name          AS assay_name,
    o.output_type,
    m.entity_id     AS output_id,
    m.entity_name   AS output_name,
    o.experimental_group,
    m.slot_name     AS measurement,
    m.value,
    m.value_num,
    m.unit,
    m.unit_label,
    m.central_tendency,
    m.sample_size,
    m.variability_type,
    m.variability_value,
    m.lower_bound,
    m.upper_bound,
    e.id                                AS exposure_id,
    e.exposure_agent                    AS exposure_agent,
    e.exposure_agent_label              AS exposure_agent_label,
    e.exposure_concentration_value      AS exposure_concentration,
    e.exposure_concentration_unit_label AS exposure_concentration_unit,
    e.exposure_duration_value           AS exposure_duration,
    e.exposure_duration_unit_label      AS exposure_duration_unit,
    a.informs_on_key_event_id           AS key_event_id,
    ke.name                             AS key_event_name,
    m.source_file
FROM measurement m
LEFT JOIN assay_output o
       ON o.source_file = m.source_file AND o.id = m.entity_id
LEFT JOIN assay a
       ON a.source_file = o.source_file AND a.id = o.assay_id
LEFT JOIN "ExposureCondition" e
       ON e.source_file = o.source_file AND e.id = o.measured_under_id
LEFT JOIN "KeyEvent" ke
       ON ke.source_file = a.source_file AND ke.id = a.informs_on_key_event_id
LEFT JOIN paper p
       ON p.source_file = m.source_file;
""".strip())

    parts.append("""
-- Evidence quotes with the entity they support, resolved to one parent column.
CREATE VIEW evidence AS
SELECT
    ev.paper_id,
    ev.parent_type,
    ev.parent_id,
    ev.parent_slot,
    ev.supports,
    ev.evidence_source,
    ev.reference,
    ev.reference_title,
    ev.snippet,
    ev.explanation,
    ev.source_file
FROM "EvidenceItem" ev;
""".strip())

    parts.append("""
-- Which ontology terms the KB actually uses, and how often. Counts every
-- reference recorded in term_ref -- units, cell types, species, chemicals and
-- anatomical entities alike -- so a term with no uses really is unused.
CREATE VIEW term_usage AS
SELECT
    t.id,
    t.label,
    t.prefix,
    COALESCE(u.n_uses, 0)   AS n_uses,
    COALESCE(u.n_papers, 0) AS n_papers,
    u.slots
FROM term t
LEFT JOIN (
    SELECT
        term_id                            AS id,
        COUNT(*)                           AS n_uses,
        COUNT(DISTINCT source_file)         AS n_papers,
        STRING_AGG(DISTINCT slot_name, ', ') AS slots
    FROM term_ref
    GROUP BY term_id
) u ON u.id = t.id;
""".strip())

    return "\n\n".join(parts) + "\n"


def _subclasses(sv, parent: str) -> list[str]:
    """Concrete descendants of an abstract parent class, in schema order."""
    return [
        c for c in sorted(table_classes(sv))
        if parent in sv.class_ancestors(c) and c != parent
    ]


def _union_view(sv, view, parent, classes, type_col, extra=None):
    """UNION ALL the subclass tables over the columns they all inherit."""
    base = [n for n, _ in columns_for(sv, parent)]
    cols = ["paper_id", "source_file", "parent_id"] + base
    selects = []
    for cls in classes:
        available = {n for n, _ in columns_for(sv, cls)} | {
            "paper_id", "source_file", "parent_id", "parent_type", "parent_slot"
        }
        exprs = [f"'{cls}' AS {type_col}"]
        for c in cols:
            exprs.append(f'"{c}"' if c in available else f'NULL AS "{c}"')
        for alias, expr in (extra or []):
            exprs.append(f'{expr} AS "{alias}"')
        selects.append(f'SELECT {", ".join(exprs)} FROM "{cls}"')
    body = "\nUNION ALL\n".join(selects)
    return f"-- {view}: all {len(classes)} {parent} subclasses in one relation.\nCREATE VIEW {view} AS\n{body};"


