def dump_tsv(db: Path, out_dir: Path) -> list[str]:
    """One .tsv per table and view.

    DuckDB's own `EXPORT DATABASE` is one command but lowercases filenames and
    writes tab-delimited data into files named `.csv`, which Excel mis-parses on
    double-click. Copying table by table keeps the class names and an honest
    extension. LIST columns are joined with '; ' so the output stays rectangular.
    """
    import duckdb

    con = duckdb.connect(str(db), read_only=True)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    rels = con.execute(
        "SELECT table_name, table_type FROM information_schema.tables "
        "WHERE table_schema = 'main' ORDER BY table_type, table_name"
    ).fetchall()
    for name, _type in rels:
        cols = con.execute(f'DESCRIBE "{name}"').fetchall()
        exprs = []
        for col, typ, *_ in cols:
            if typ.endswith("[]"):
                exprs.append(f'array_to_string("{col}", \'; \') AS "{col}"')
            else:
                exprs.append(f'"{col}"')
        target = out_dir / f"{name}.tsv"
        con.execute(
            f'COPY (SELECT {", ".join(exprs)} FROM "{name}") '
            f"TO '{target}' (FORMAT CSV, DELIMITER '\t', HEADER, QUOTE '\"')"
        )
        written.append(target.name)
    con.close()
    return written


