#!/usr/bin/env python3
"""Build a local DuckDB database from the kb/publications/ YAML knowledge base.

The YAML files are the source of truth; this database is a generated product,
rebuilt by `just build-db` and never hand-edited.

Layers
------
L1  One table per concrete LinkML class, with value objects flattened into
    named columns (see scripts/soma_duckdb.py for the mapping rules), plus
    three tables the schema does not itself declare:

      measurement  long-format: one row per number anywhere in the KB, with
                   its unit, dispersion, central tendency and sample size.
                   The wide tables carry a compact 3-column echo of the same
                   value for ergonomic wide queries; this table is canonical.
      link         every entity-to-entity edge (parent_type, parent_id,
                   parent_slot, target_type, target_id). Authoritative for
                   many-to-many relationships such as follows_protocols.
      term         every ontology term the KB references, with its label.

L2  Views that make the layered model queryable without knowing the schema:
    assay, assay_output, measurement_full, evidence, term_usage.

Usage:
    uv run python scripts/build_duckdb.py                       # kb/ (or tests/data/valid if empty)
    uv run python scripts/build_duckdb.py --kb-dir tests/data/valid
    uv run python scripts/build_duckdb.py --ddl-only            # print DDL, build nothing
"""
