MEASUREMENT_DDL = """
CREATE TABLE measurement (
    paper_id      VARCHAR,
    source_file   VARCHAR,
    entity_type   VARCHAR,
    entity_id     VARCHAR,
    entity_name   VARCHAR,
    slot_name     VARCHAR,
    value         VARCHAR,
    value_num     DOUBLE,
    value_qualifier VARCHAR,
    min_value     VARCHAR,
    max_value     VARCHAR,
    unit          VARCHAR,
    unit_label    VARCHAR,
    central_tendency   VARCHAR,
    sample_size        BIGINT,
    variability_type   VARCHAR,
    variability_value  VARCHAR,
    lower_bound        VARCHAR,
    upper_bound        VARCHAR
);
CREATE TABLE link (
    paper_id     VARCHAR,
    source_file  VARCHAR,
    parent_type  VARCHAR,
    parent_id    VARCHAR,
    parent_slot  VARCHAR,
    target_type  VARCHAR,
    target_id    VARCHAR,
    inlined      BOOLEAN
);
CREATE TABLE term (
    id          VARCHAR PRIMARY KEY,
    label       VARCHAR,
    prefix      VARCHAR
);
-- Every ontology term reference, so term_usage can count all of them rather
-- than only the ones that happened to be units.
CREATE TABLE term_ref (
    paper_id     VARCHAR,
    source_file  VARCHAR,
    entity_type  VARCHAR,
    entity_id    VARCHAR,
    slot_name    VARCHAR,
    term_id      VARCHAR
);
-- Keyed on source_file, not the cited PMID: two kb files may legitimately cite
-- one paper (a re-extraction, or a paper split across files), and keying on the
-- PMID would either abort the build on a primary-key clash or silently merge
-- the two files' entities into each other. paper_id stays as an attribute.
CREATE TABLE paper (
    source_file     VARCHAR PRIMARY KEY,
    paper_id        VARCHAR,
    reference       VARCHAR,
    reference_title VARCHAR,
    doi             VARCHAR
);
"""


def emit_ddl(sv) -> str:
    """Generate the L1 DDL from the schema."""
    parts = [
        "-- Generated by scripts/build_duckdb.py from the soma-schema LinkML schema.",
        "-- Do not edit: regenerate with `just db-schema`.",
        MEASUREMENT_DDL.strip(),
        "",
    ]
    for cls in sorted(table_classes(sv)):
        cols = list(PROVENANCE_COLUMNS) + list(PARENT_COLUMNS) + columns_for(sv, cls)
        seen, deduped = set(), []
        for name, typ in cols:
            if name in seen:
                continue
            seen.add(name)
            deduped.append((name, typ))
        lines = [f'    "{n}" {t}' for n, t in deduped]
        if has_natural_key(sv, cls):
            lines.append('    PRIMARY KEY ("source_file", "id")')
        body = ",\n".join(lines)
        parts.append(f'CREATE TABLE "{cls}" (\n{body}\n);')
    return "\n".join(parts) + "\n"


