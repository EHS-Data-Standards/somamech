# ---------------------------------------------------------------------------

def _execute_script(con, script: str):
    """Run a multi-statement script, skipping -- comment lines.

    The comment lines matter: LinkML-style DDL comments contain semicolons and
    prose, so they must be stripped before splitting rather than after.
    """
    clean = "\n".join(
        l for l in script.splitlines() if not l.lstrip().startswith("--")
    )
    for stmt in (s.strip() for s in clean.split(";")):
        if stmt:
            con.execute(stmt)


def _insert(con, table, rows):
    if not rows:
        return 0
    cols = [r[0] for r in con.execute(f'DESCRIBE "{table}"').fetchall()]
    placeholders = ", ".join("?" for _ in cols)
    payload = [tuple(r.get(c) for c in cols) for r in rows]
    con.executemany(
        f'INSERT INTO "{table}" ({", ".join(chr(34)+c+chr(34) for c in cols)}) '
        f"VALUES ({placeholders})",
        payload,
    )
    return len(payload)


def build(kb_dir: Path, out: Path, schema_path: str) -> dict:
    import duckdb

    sv = load_schema(schema_path)
    files = sorted(kb_dir.glob("*.yaml"))
    if not files:
        raise SystemExit(f"No YAML files in {kb_dir} — nothing to build.")

    b = Builder(sv)
    for f in files:
        b.add_file(f)

    out.parent.mkdir(parents=True, exist_ok=True)
    out.unlink(missing_ok=True)
    con = duckdb.connect(str(out))
    _execute_script(con, emit_ddl(sv))

    counts = {}
    counts["paper"] = _insert(con, "paper", b.papers)
    for cls, rowmap in b.rows.items():
        n = _insert(con, cls, list(rowmap.values()))
        if n:
            counts[cls] = n
    counts["measurement"] = _insert(con, "measurement", b.measurements)
    counts["link"] = _insert(con, "link", b.links)
    counts["term"] = _insert(
        con, "term",
        [{"id": k, "label": v[0], "prefix": v[1]} for k, v in sorted(b.terms.items())],
    )
    _execute_script(con, emit_views(sv))
    con.close()
    return {"files": len(files), "counts": counts, "warnings": b.warnings}


